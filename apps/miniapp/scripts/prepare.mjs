import { readFileSync, writeFileSync } from "node:fs";

const root = new URL("../", import.meta.url);
const config = JSON.parse(
  readFileSync(new URL("config.local.json", root), "utf8").replace(
    /^\uFEFF/,
    "",
  ),
);
const origin = new URL(config.apiOrigin);
if (
  origin.protocol !== "https:" ||
  origin.pathname !== "/" ||
  origin.search ||
  origin.hash ||
  origin.username ||
  origin.password
)
  throw new Error("apiOrigin must be an HTTPS origin");
for (const media of Object.values(config.storeMedia || {})) {
  if (media.image && new URL(media.image).protocol !== "https:")
    throw new Error("Store images must use HTTPS media URLs");
}
writeFileSync(
  new URL("config.js", root),
  `// Generated by prepare:config; do not commit.\nmodule.exports = ${JSON.stringify({ apiOrigin: origin.origin, storeMedia: config.storeMedia || {} }, null, 2)};\n`,
);
